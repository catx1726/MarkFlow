let previousTabId = 0

// communication example: send previous tab title from background page
// see shim.d.ts for type declaration
browser.tabs.onActivated.addListener(async ({ tabId }) => {
  if (!previousTabId) {
    previousTabId = tabId
    return
  }

  let tab: Tabs.Tab

  try {
    tab = await browser.tabs.get(previousTabId)
    previousTabId = tabId
  } catch {
    return
  }

  // eslint-disable-next-line no-console
  console.log('previous tab', tab)
  sendMessage('tab-prev', { title: tab.title }, { context: 'content-script', tabId })
})

onMessage('get-current-tab', async () => {
  try {
    const tab = await browser.tabs.get(previousTabId)
    return {
      title: tab?.title
    }
  } catch {
    return {
      title: undefined
    }
  }
})

/**
 * 核心：处理自动标签晋升逻辑 (V3 优化版)
 * - 使用防抖机制
 * - 减少响应式触发
 * - 仅在晋升时全量扫描
 */
let autoTaggingTimer: any = null
async function debouncedAutoTagging(mark: Mark) {
  if (autoTaggingTimer) clearTimeout(autoTaggingTimer)
  autoTaggingTimer = setTimeout(() => {
    processAutoTagging(mark)
  }, 1500) // 1.5秒防抖，降低处理频率
}

async function processAutoTagging(mark: Mark) {
  try {
    const domain = new URL(mark.url).hostname
    const keywords = extractKeywords(`${mark.title} ${mark.text}`)
    let needsPersistence = false
    let hasNewTagCreated = false

    // 复制一份镜像，避免循环中触发多次持久化
    const statsUpdate = { ...keywordStats.value }
    const tagsUpdate = { ...tagsMetadata.value }
    const marksUpdate = { ...marksByUrl.value }

    for (const kw of keywords) {
      const key = kw.toLowerCase()
      if (!statsUpdate[key]) {
        statsUpdate[key] = { count: 0, domains: [] }
      }

      const stat = statsUpdate[key]
      stat.count++
      if (!stat.domains.includes(domain)) {
        stat.domains.push(domain)
      }
      needsPersistence = true

      // 检查是否达到晋升阈值
      if (shouldPromoteToTag({ count: stat.count, domains: new Set(stat.domains) })) {
        let existingTag = Object.values(tagsUpdate).find(t => t.name.toLowerCase() === key)

        if (!existingTag) {
          const tagId = `auto-tag-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`
          existingTag = {
            id: tagId,
            name: kw,
            color: '#10B981',
            isAutoGenerated: true,
            createdAt: Date.now()
          }
          tagsUpdate[tagId] = existingTag
          hasNewTagCreated = true
          
          // 仅在创建新标签时，对内存镜像进行一次扫描关联
          Object.entries(marksUpdate).forEach(([url, pageMarks]) => {
            marksUpdate[url] = pageMarks.map(m => {
              if ((m.text.toLowerCase().includes(key) || m.title?.toLowerCase().includes(key))) {
                const currentTags = m.tags || []
                if (!currentTags.includes(tagId)) {
                  return { ...m, tags: [...currentTags, tagId] }
                }
              }
              return m
            })
          })
        }
      }
    }

    if (needsPersistence) {
      keywordStats.value = statsUpdate
      if (hasNewTagCreated) {
        tagsMetadata.value = tagsUpdate
        marksByUrl.value = marksUpdate
      }
    }
  } catch (e) {
    console.error('[background] Error in auto-tagging logic:', e)
  }
}

/**
 * 核心：清理关键词统计信息 (V3 优化版)
 * - 严谨重新计算域名相关性
 */
function cleanupKeywordStats(mark: Mark) {
  const domain = new URL(mark.url).hostname
  const keywords = extractKeywords(`${mark.title} ${mark.text}`)
  let needsPersistence = false
  const statsUpdate = { ...keywordStats.value }

  for (const kw of keywords) {
    const key = kw.toLowerCase()
    const stat = statsUpdate[key]
    if (stat) {
      stat.count = Math.max(0, stat.count - 1)
      
      // 重新验证该域名是否还应保留在该关键词下
      const domainStillHasKeyword = Object.entries(marksByUrl.value)
        .filter(([url]) => new URL(url).hostname === domain)
        .some(([_, pageMarks]) => pageMarks.some(m => m.id !== mark.id && (m.text.toLowerCase().includes(key) || m.title?.toLowerCase().includes(key))))
      
      if (!domainStillHasKeyword) {
        stat.domains = stat.domains.filter(d => d !== domain)
      }
      
      if (stat.count === 0 || stat.domains.length === 0) {
        delete statsUpdate[key]
      }
      needsPersistence = true
    }
  }
  if (needsPersistence) {
    keywordStats.value = statsUpdate
  }
}

onMessage('add-mark', async ({ data }) => {
  const { url } = data
  if (!marksByUrl.value[url]) marksByUrl.value[url] = []

  marksByUrl.value[url].push(data)
  marksByUrl.value = { ...marksByUrl.value } 

  // 异步防抖处理自动标签
  debouncedAutoTagging(data)
})

onMessage('remove-mark', async ({ data: markToRemove }) => {
  const { url, id } = markToRemove
  if (marksByUrl.value[url]) {
    const mark = marksByUrl.value[url].find(m => m.id === id)
    if (mark) {
      cleanupKeywordStats(mark)
      marksByUrl.value[url] = marksByUrl.value[url].filter((m) => m.id !== id)
      if (marksByUrl.value[url].length === 0) delete marksByUrl.value[url]
      marksByUrl.value = { ...marksByUrl.value }
    }
  }
})

onMessage('get-marks-for-url', async ({ data }) => {
  await dataReady
  const { url } = data
  return (marksByUrl.value[url] || []).map(toRaw)
})

onMessage<RemoveMarkPayload>('remove-mark-by-id', async ({ data }) => {
  const { url, id } = data
  if (marksByUrl.value[url]) {
    const mark = marksByUrl.value[url].find(m => m.id === id)
    if (mark) {
      cleanupKeywordStats(mark)
      marksByUrl.value[url] = marksByUrl.value[url].filter((m) => m.id !== id)
      if (marksByUrl.value[url].length === 0) delete marksByUrl.value[url]
      marksByUrl.value = { ...marksByUrl.value }
    }
  }
})

onMessage<UpdateMarkNotePayload>('update-mark-note', async ({ data }) => {
  const { url, id, note } = data
  if (marksByUrl.value[url]) {
    const markToUpdate = marksByUrl.value[url].find((m) => m.id === id)
    if (markToUpdate) {
      markToUpdate.note = note
      marksByUrl.value = { ...marksByUrl.value }
    }
  }
})

onMessage<any>('update-mark-details', async ({ data }) => {
  const { url, id, ...updates } = data
  if (marksByUrl.value[url]) {
    const index = marksByUrl.value[url].findIndex((m) => m.id === id)
    if (index !== -1) {
      const markToUpdate = marksByUrl.value[url][index]
      Object.assign(markToUpdate, updates)
      marksByUrl.value = { ...marksByUrl.value }
      console.log(`[background] Mark ${id} updated successfully`)
    }
  }
})

onMessage<GetMarkByIdPayload>('get-mark-by-id', async ({ data }) => {
  const { url, id } = data
  if (marksByUrl.value[url]) {
    const markProxy = marksByUrl.value[url].find((m) => m.id === id)
    if (markProxy) return toRaw(markProxy)
  }
  return undefined
})

onMessage('get-storage-usage', async () => {
  const usage = await browser.storage.local.getBytesInUse()
  const rawQuota = (browser.storage.local as any).QUOTA_BYTES
  const quota = typeof rawQuota === 'number' ? rawQuota : 10 * 1024 * 1024
  return { usage, quota }
})

onMessage('cleanup-old-marks', async ({ data }) => {
  const { days } = data
  const threshold = Date.now() - days * 24 * 60 * 60 * 1000
  const allMarks = marksByUrl.value
  const keptMarks = Object.values(allMarks)
    .flat()
    .filter((mark: Mark) => mark.createdAt > threshold)

  marksByUrl.value = keptMarks.reduce((acc, mark) => {
    if (!acc[mark.url]) acc[mark.url] = []
    acc[mark.url].push(mark)
    return acc
  }, {} as Record<string, Mark[]>)
})

onMessage('cleanup-useless-marks', () => {
  const allMarks = marksByUrl.value
  const keptMarks = Object.values(allMarks)
    .flat()
    .filter((mark: Mark) => mark.note && mark.note.trim() !== '')

  marksByUrl.value = keptMarks.reduce((acc, mark) => {
    if (!acc[mark.url]) acc[mark.url] = []
    acc[mark.url].push(mark)
    return acc
  }, {} as Record<string, Mark[]>)
})

onMessage<{ tabId: number }>('open-sidepanel', async ({ data }) => {
  const { tabId } = data
  if (!tabId) return { success: false, error: 'Tab ID missing' }

  try {
    // @ts-expect-error missing types
    if (browser.sidePanel && typeof (browser.sidePanel as any).open === 'function') {
      // @ts-expect-error missing types
      await (browser.sidePanel as any).open({ tabId })
      return { success: true, browser: 'Chrome' }
    }
    return { success: false, error: 'Side panel/Sidebar API not found.' }
  } catch (e) {
    console.error('Failed to open side panel/sidebar:', e)
    return { success: false, error: `API call failed: ${(e as Error).message}` }
  }
})

onMessage<{ url: string }>('remove-marks-by-url', async ({ data }) => {
  const { url } = data
  if (marksByUrl.value[url]) {
    marksByUrl.value[url].forEach(cleanupKeywordStats)
    delete marksByUrl.value[url]
    marksByUrl.value = { ...marksByUrl.value }
  }
})

onMessage('get-all-marks', async () => {
  await dataReady
  const result: Record<string, Mark[]> = {}
  Object.entries(marksByUrl.value).forEach(([url, marks]) => {
    result[url] = marks.map(toRaw)
  })
  return result
})

